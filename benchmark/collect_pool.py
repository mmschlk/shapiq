"""Collect terminal pooled results without changing scientific inputs or retrying cells.

``collect(config, store)`` returns a sanitized report and one consolidated check.
Config pins suite/source and the inventory generated by the frozen pool launcher. Jobs name existing registration/admission evidence.
A partial collection reports unresolved cases and never claims publication readiness.
"""

from __future__ import annotations

import copy
import hashlib
import importlib.util
import itertools
import json
import math
import subprocess
import sys
from collections import Counter
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from shapiq_benchmark.record_store import RecordStore

KEYS = ("game_id", "method", "budget", "seed")
TERMINAL = {
    "COMPLETED",
    "FAILED",
    "TIMEOUT",
    "CANCELLED",
    "OUT_OF_MEMORY",
    "NODE_FAIL",
    "PREEMPTED",
    "BOOT_FAIL",
    "DEADLINE",
    "REVOKED",
}


def require(condition: object, message: str) -> None:
    """Reject inconsistent evidence before returning a report."""
    if not condition:
        raise ValueError(message)


def digest(path: str | Path) -> str:
    """Hash files in bounded blocks."""
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


class Inputs:
    """Remember every consumed byte and absence for a final stability check."""

    def __init__(self) -> None:
        """Start an empty consumed-input inventory."""
        self.hashes, self.absent = {}, set()

    def pin(self, path: str | Path, expected: str | None = None) -> Path:
        """Authenticate one input and retain its observed hash."""
        path = Path(path).absolute()
        actual = digest(path)
        require(expected is None or actual == expected, f"Input hash differs: {path}")
        require(
            str(path) not in self.hashes or self.hashes[str(path)] == actual,
            f"Input changed: {path}",
        )
        self.hashes[str(path)] = actual
        return path

    def read(self, path: str | Path, *, optional: bool = False) -> dict | list | None:
        """Read JSON or record an explicitly permitted absence."""
        path = Path(path).absolute()
        if optional and not path.exists():
            require(not path.is_symlink(), "Missing input is a dangling symlink")
            self.absent.add(str(path))
            return None
        return json.loads(self.pin(path).read_text())

    def pinned(self, entry: dict) -> dict | list:
        """Read a caller-pinned input."""
        return self.read(self.pin(entry["path"], entry["sha256"]))

    def stable(self) -> None:
        """Reject final byte or absence changes."""
        require(
            all(digest(p) == sha for p, sha in self.hashes.items()), "Collection inputs changed"
        )
        require(
            not any(Path(p).exists() or Path(p).is_symlink() for p in self.absent),
            "Previously absent input appeared",
        )


def terminal_accounting(jobs: dict) -> dict:
    """Query all live IDs first, then require exact terminal accounting for each owner."""
    live = set(
        subprocess.check_output(  # noqa: S603 -- fixed read-only scheduler query
            ["squeue", "--me", "--array", "--noheader", "--format=%i"],  # noqa: S607
            text=True,
        ).split()
    )
    require(not live.intersection(jobs), "Pool allocation is still live")
    raw = subprocess.check_output(  # noqa: S603 -- fixed read-only scheduler query
        [  # noqa: S607 -- scheduler executable on the cluster PATH
            "sacct",
            "-X",
            "-n",
            "-P",
            "--array",
            "-j",
            ",".join(sorted(jobs)),
            "-o",
            "JobIDRaw,State,ExitCode,AllocCPUS,CPUTimeRAW,NodeList",
        ],
        text=True,
    )
    result = {}
    for line in raw.splitlines():
        job, state, exit_code, cpus, cpu_seconds, node, *_ = line.split("|")
        if job not in jobs:
            continue
        require(
            job not in result and state.split()[0] in TERMINAL,
            "Missing or ambiguous terminal accounting",
        )
        result[job] = {
            "state": state,
            "exit_code": exit_code,
            "cpus": int(cpus),
            "cpu_seconds": int(cpu_seconds),
            "node": node,
        }
    require(set(result) == set(jobs), "Terminal accounting omitted an admitted job")
    return result


def frozen_inventory(config: dict, suite: dict, inputs: Inputs) -> list[dict]:
    """Use frozen queue ordering; independently check complete recipe/seed membership."""
    if "inventory" in config:
        inventory = inputs.pinned(config["inventory"])
    else:
        modules = []
        for key in ("prepare_script", "pool_script"):
            pin = config[key]
            path = inputs.pin(pin["path"], pin["sha256"])
            spec = importlib.util.spec_from_file_location("collection_" + key, path)
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            modules.append(module)
        previous = sys.modules.get("prepare_matrix")
        sys.modules["prepare_matrix"] = modules[0]
        try:
            inventory = modules[1].tasks(suite)
        finally:
            if previous is None:
                sys.modules.pop("prepare_matrix", None)
            else:
                sys.modules["prepare_matrix"] = previous
    recipes = {r["id"]: r for r in suite["focused_design"]["recipes"]}
    expected = {}
    for spec in suite["families"]:
        for seed in suite["game_seeds"]:
            expected[spec["id"], seed] = ("family", [spec])
    for spec in suite["games"]:
        for seed in suite["game_seeds"]:
            kind, specs = expected.setdefault((spec["basecase_id"], seed), ("structured", []))
            require(kind == "structured", "Family/native recipe overlap")
            specs.append(spec)
    actual = {}
    for task in inventory:
        key = task["recipe"], task["seed"]
        require(key not in actual and task["recipe"] in recipes, "Repeated or foreign pool task")
        actual[key] = task["kind"], task["specs"]
        require(task["spec"] == task["specs"][0], "Task primary specification differs")
    require(
        actual == expected and len(expected) == len(recipes) * len(suite["game_seeds"]),
        "Incomplete pool recipe/seed inventory",
    )
    require(
        sorted(t["case"] for t in inventory) == list(range(len(inventory))),
        "Missing or repeated pool case number",
    )
    return sorted(inventory, key=lambda t: t["case"])


def fragment(suite: dict, task: dict) -> dict:
    """Reproduce the pool fragment without changing its scientific settings."""
    result = {
        k: copy.deepcopy(v)
        for k, v in suite.items()
        if not k.startswith("matrix_") and k not in ("families", "games")
    }
    result["game_seeds"] = [task["seed"]]
    result["games"] = task["specs"] if task["kind"] == "structured" else []
    if task["kind"] == "family":
        result["families"] = [task["spec"]]
    result["focused_design"]["recipes"] = [
        r for r in suite["focused_design"]["recipes"] if r["id"] == task["recipe"]
    ]
    return result


def journal(path: Path, inputs: Inputs) -> tuple[list[dict], bool]:
    """Retain complete lines, recording a trailing interruption without discarding evidence."""
    path = Path(path)
    if not path.exists():
        require(not path.is_symlink(), "Missing journal is a dangling symlink")
        inputs.absent.add(str(path.absolute()))
        return [], False
    inputs.pin(path)
    rows, tail = [], False
    with path.open("rb") as stream:
        for line in stream:
            if not line.endswith(b"\n"):
                tail = True
                break
            rows.append(json.loads(line))
    return rows, tail


def checkpoint(path: Path, snapshot: dict, inputs: Inputs) -> tuple[dict | None, bool]:
    """Read closed checkpoints normally; authenticate committed prefixes after interruption.

    Interrupted data become a distinct derived view. This never invokes runner
    recovery or writes its manifest/journal, and never treats a changed committed
    prefix as an operational tail.
    """
    from shapiq_benchmark.results_io import read_results, result_inputs

    header = inputs.read(path, optional=True)
    if header is None:
        rows, _ = journal(path.parent / "records.jsonl", inputs)
        require(not rows, "Raw result records without a manifest require reconciliation")
        return None, False
    for item in result_inputs(path):
        inputs.pin(item)
    try:
        return read_results(path), True
    except ValueError as error:
        if "journal" not in str(error).lower():
            raise
    require(
        header.get("storage_format") == "snapshot-journal-v1", "Unknown interrupted result format"
    )
    expected = header["journal"]
    sha = hashlib.sha256()
    count = 0
    with (path.parent / "records.jsonl").open("rb") as stream:
        for _ in range(expected["records"]):
            line = stream.readline()
            require(line.endswith(b"\n"), "Interrupted previously committed result prefix")
            sha.update(line)
            count += 1
    require(
        count == expected["records"] and sha.hexdigest() == expected["sha256"],
        "Changed committed result prefix",
    )
    require(
        header["snapshot_id"] == snapshot["snapshot_id"]
        and header["snapshot_file_sha256"]
        == digest((path.parent / header["snapshot_file"]).resolve()),
        "Interrupted snapshot differs",
    )
    rows, _ = journal(path.parent / "records.jsonl", inputs)
    raw = {
        k: v
        for k, v in header.items()
        if k not in ("storage_format", "snapshot_file", "snapshot_file_sha256", "journal")
    }
    raw.update(
        {key: snapshot.get(key, []) for key in ("suite", "games", "coverage")},
        snapshot_provenance=snapshot["provenance"],
        records=rows,
    )
    return raw, False


def worker_matches(worker: dict, claim: dict, allocation: dict) -> None:
    """Check actual worker placement against its admitted claim."""
    require(
        worker["slurm_job_id"] == claim["job"]
        and worker["hostname"] == claim["hostname"]
        and worker["affinity"] == [claim["cpu"]]
        and claim["cpu"] in allocation["cpus"],
        "Worker ownership/hardware differs",
    )
    require(
        worker.get("cpu_model") and worker.get("machine") == "x86_64", "Missing worker CPU identity"
    )
    from shapiq_benchmark.execution import THREAD_VARIABLES

    require(
        all(worker["thread_environment"].get(name) == "1" for name in THREAD_VARIABLES)
        and all(pool["num_threads"] == 1 for pool in worker["thread_pools"]),
        "Worker thread limits differ",
    )


def validate_scores(row: dict, game: dict) -> None:
    """Recompute saved whole-vector/order errors without fitting or changing the game."""
    from shapiq import InteractionValues
    from shapiq_benchmark.runner import score

    for name in (
        "seconds",
        "wall_seconds",
        "cache_lookup_seconds",
        "estimated_oracle_seconds",
        "estimated_uncached_seconds",
    ):
        value = row.get(name)
        require(
            value is None or (type(value) in (int, float) and math.isfinite(value) and value >= 0),
            "Invalid timing measurement",
        )
    for name in ("queries", "requested_queries"):
        value = row.get(name)
        require(value is None or (type(value) is int and value >= 0), "Invalid query counter")
    require(
        row.get("queries") is None or row["queries"] <= row["budget"],
        "Actual queries exceed allowance",
    )
    if row["status"] != "ok":
        require(
            all(row.get(k) is None for k in ("nmse", "mse", "estimate", "order_scores")),
            "Unsuccessful row contains scores",
        )
        return
    encoded = row["estimate"]
    keys = [tuple(k) for k in encoded["coordinates"]]
    require(len(keys) == len(set(keys)) == len(encoded["values"]), "Repeated estimate coordinates")
    values = dict(zip(keys, encoded["values"], strict=True))
    estimate = InteractionValues(
        values,
        index=game["index"],
        max_order=game["order"],
        n_players=game["n_players"],
        min_order=0,
        baseline_value=values.get((), 0.0),
    )

    def equal(a: object, b: object) -> bool:
        if isinstance(b, dict):
            return (
                isinstance(a, dict)
                and a.keys() == b.keys()
                and all(equal(a[k], v) for k, v in b.items())
            )
        if isinstance(b, float):
            return (
                type(a) in (int, float)
                and math.isfinite(a)
                and math.isclose(a, b, rel_tol=1e-12, abs_tol=1e-30)
            )
        return a == b

    require(
        all(equal(row.get(k), v) for k, v in score(estimate, game).items()),
        "Saved scores disagree with frozen coefficients",
    )
    require(
        type(row["queries"]) is int
        and type(row["requested_queries"]) is int
        and 0 <= row["queries"] <= row["requested_queries"] <= row["budget"],
        "Estimator exceeded query allowance",
    )


def collect(config: dict, store: RecordStore) -> tuple[dict, dict]:
    """Assemble exactly the configured pool; store is an open disposable RecordStore.

    Pin entries use {path, sha256}. jobs maps numeric job IDs to registration and
    intent pins. operational_receipts entries contain receipt/hook/archive pins.
    Partial inventories are inspectable but never complete or publication-ready.
    """
    require(
        config["jobs"] and all(job.isdigit() for job in config["jobs"]) and len(store) == 0,
        "Need numeric admitted jobs and an empty record store",
    )
    accounting = terminal_accounting(config["jobs"])  # Before opening any task journal.
    from shapiq_benchmark.report import merge_results
    from shapiq_benchmark.runner import (
        cell_timeout,
        identity,
        load_snapshot,
        method_catalog,
        provenance,
    )

    inputs = Inputs()
    suite, source = inputs.pinned(config["suite"]), inputs.pinned(config["source"])
    require(
        provenance() == source, "Collector must run under the exact frozen scientific provenance"
    )
    require(not suite.get("duplicate_registry"), "Unexpected shared duplicate registry")
    inventory = frozen_inventory(config, suite, inputs)
    root = Path(config["pool_directory"]).absolute()
    starts = {}
    require(
        {p.name for p in (root / "allocations").iterdir()} == set(config["jobs"]),
        "Foreign or missing allocation directory",
    )
    for job, evidence in config["jobs"].items():
        registration, admission = (
            inputs.pinned(evidence["registration"]),
            inputs.pinned(evidence["intent"]),
        )
        require(
            registration["job"] == job and registration["cpus"] == accounting[job]["cpus"],
            "Job registration differs",
        )
        command = admission["command"]
        inputs.pin(command[-1], admission["script_sha256"])
        require(
            f"--cpus-per-task={registration['cpus']}" in command
            and f"--nodelist={accounting[job]['node']}" in command,
            "Admitted allocation differs",
        )
        start = inputs.read(root / "allocations" / job / "started.json")
        require(
            start["job"] == job
            and start["suite_sha256"] == config["suite"]["sha256"]
            and start["source_sha256"] == config["source"]["sha256"]
            and start["hostname"].split(".")[0] == accounting[job]["node"]
            and len(start["cpus"])
            == len(set(start["cpus"]))
            == start["workers"]
            <= registration["cpus"],
            "Allocation startup differs",
        )
        inputs.read(root / "allocations" / job / "finished.json", optional=True)
        starts[job] = start
    for entry in config.get("operational_receipts", []):
        receipt = inputs.pinned(entry["receipt"])
        inputs.pin(entry["hook"]["path"], entry["hook"]["sha256"])
        inputs.pin(entry["archive"]["path"], entry["archive"]["sha256"])
        require(
            receipt["job"] in starts
            and receipt["hostname"] == starts[receipt["job"]]["hostname"]
            and receipt["source_provenance_exact_match"] is True
            and receipt["original_dependency_bytes_unchanged"] is True
            and receipt["probe"]["source_sha256"] == source["source_sha256"]
            and receipt["hook_sha256"] == entry["hook"]["sha256"]
            and receipt["archive_sha256"] == entry["archive"]["sha256"],
            "Operational repair does not preserve exact source",
        )
    for path, sha in config.get("input_hashes", {}).items():
        inputs.pin(path, sha)
    names = {f"case-{task['case']:06d}" for task in inventory}
    actual_directories = {p.name for p in (root / "tasks").iterdir()}
    require(
        actual_directories <= names, "Foreign task directory outside the comprehensive inventory"
    )
    data = {
        "schema_version": 1,
        "snapshot_provenance": source,
        "suite": copy.deepcopy(suite),
        "games": [],
        "coverage": [],
        "methods": {},
        "runs": {},
        "records": store,
    }
    data["suite"].update(budgets=[], budgets_by_game={})
    catalog, cases, game_ids = method_catalog(), [], set()
    counts = Counter()
    for task in inventory:
        directory = root / "tasks" / f"case-{task['case']:06d}"
        check = {
            "case": task["case"],
            "recipe": task["recipe"],
            "seed": task["seed"],
            "complete": False,
        }
        cases.append(check)
        claim = inputs.read(directory / "claim.json", optional=True)
        if claim is None:
            check["status"] = "unclaimed" if not directory.exists() else "interrupted_claim"
            continue
        require(
            claim["task"] == task and claim["job"] in starts, "Task claim differs from inventory"
        )
        allocation = starts[claim["job"]]
        require(
            claim["cpu"] in allocation["cpus"]
            and claim["hostname"] == allocation["hostname"]
            and all(claim[k] == allocation[k] for k in ("source_sha256", "suite_sha256")),
            "Claim ownership differs",
        )
        check["job"] = claim["job"]
        declared = inputs.read(directory / "suite.json", optional=True)
        if declared is None:
            check["status"] = "interrupted_claim"
            continue
        require(declared == fragment(suite, task), "Task scientific fragment differs")
        outcome = inputs.read(directory / "outcome.json", optional=True)
        check["outcome"] = outcome
        prep_execution = inputs.read(directory / "preparation-execution.json", optional=True)
        inputs.read(directory / "evaluation-execution.json", optional=True)
        prepared = inputs.read(directory / "prepared.json", optional=True)
        if prepared is None:
            for name in (
                "intents.jsonl",
                "responses.jsonl",
                "results/results.json",
                "results/records.jsonl",
            ):
                path = directory / name
                require(
                    not path.exists() and not path.is_symlink(),
                    "Unprepared case contains evaluation evidence",
                )
                inputs.absent.add(str(path))
            require(
                not outcome or outcome["status"] != "complete",
                "False completion without preparation",
            )
            check["status"] = (outcome or {}).get("status", "preparation_interrupted")
            check["complete"] = bool(
                outcome
                and outcome["status"] in {"preparation_failed", "preparation_timeout"}
                and prep_execution == outcome.get("preparation")
                and prep_execution["returncode"] != 0
            )
            check["score_complete"] = False
            data["coverage"].append(
                {
                    "family": task["recipe"],
                    "instance_seed": task["seed"],
                    "status": "not_measured",
                    "reason": check["status"],
                }
            )
            continue
        snapshot_path = inputs.pin(
            directory / "prepared/snapshot.json", prepared["snapshot_sha256"]
        )
        snapshot, artifact_root = load_snapshot(snapshot_path)
        require(
            snapshot["snapshot_id"] == prepared["snapshot_id"]
            and snapshot["provenance"] == prepared["source"] == source,
            "Prepared source/identity differs",
        )
        require(
            {k: v for k, v in snapshot["suite"].items() if k not in ("budgets", "budgets_by_game")}
            == declared,
            "Prepared suite differs",
        )
        games = {g["id"]: g for g in snapshot["games"]}
        require(
            len(games) == len(snapshot["games"]) == prepared["targets"]
            and games
            and not set(games).intersection(game_ids),
            "Missing/repeated prepared game",
        )
        game_ids.update(games)
        for name, sha in snapshot["artifacts"].items():
            inputs.pin(artifact_root / name, sha)
        expected_panel = (
            {
                (
                    f"{task['recipe']}-i{task['seed']}-{target['index'].lower()}-{target['order']}",
                    target["index"],
                    target["order"],
                    task["spec"]["n_players"],
                )
                for target in suite["targets"]
            }
            if task["kind"] == "family"
            else {
                (spec["id"] + f"-i{task['seed']}", spec["index"], spec["order"], spec["n_players"])
                for spec in task["specs"]
            }
        )
        require(
            {(g["id"], g["index"], g["order"], g["n_players"]) for g in games.values()}
            == expected_panel,
            "Prepared target panel differs",
        )
        recipe = next(r for r in suite["focused_design"]["recipes"] if r["id"] == task["recipe"])
        for game in games.values():
            require(
                game["metadata"]["focused_design"]
                == {k: recipe[k] for k in ("application", "subtype")} | {"recipe": recipe["id"]}
                and game["metadata"]["instance_seed"] == task["seed"],
                "Weighting metadata differs",
            )
        grids = {
            gid: sorted({math.ceil(r * g["n_players"]) for r in suite["relative_budgets"]})
            for gid, g in games.items()
        }
        require(snapshot["suite"]["budgets_by_game"] == grids, "Query grids differ")
        planned = {
            (gid, method, budget, seed)
            for gid, method in itertools.product(games, suite["methods"])
            for budget, seed in itertools.product(grids[gid], suite["seeds"])
        }
        supported = {key for key in planned if games[key[0]]["index"] in catalog[key[1]]["indices"]}
        intents, intent_tail = journal(directory / "intents.jsonl", inputs)
        responses, response_tail = journal(directory / "responses.jsonl", inputs)
        attempted, returned = {}, {}
        for sequence, intent in enumerate(intents, 1):
            key = tuple(intent[k] for k in KEYS)
            require(
                intent["sequence"] == sequence and key in supported and key not in attempted,
                "Duplicate/foreign/unsupported launch intent",
            )
            require(
                intent["slurm_job_id"] == claim["job"]
                and intent["cpu"] == claim["cpu"]
                and intent["expected_snapshot_id"] == snapshot["snapshot_id"]
                and intent["expected_source_hash"] == source["source_sha256"]
                and intent["method_parameters"] == suite.get("method_parameters", {}).get(key[1])
                and intent["timeout"]
                == cell_timeout(games[key[0]], key[2], 30, suite["cell_timeout_policy"]),
                "Launch intent differs from frozen cell",
            )
            attempted[key] = intent
        for response in responses:
            key = tuple(response["cell"])
            require(
                key in attempted
                and key not in returned
                and response["sequence"] == attempted[key]["sequence"],
                "Response lacks one unique matching intent",
            )
            require(
                response["response"]["status"] in {"ok", "failed"}, "Unexpected response status"
            )
            require(
                all(
                    response["response"].get(name, value) == value
                    for name, value in zip(KEYS, key, strict=True)
                ),
                "Response overwrites cell identity",
            )
            returned[key] = response["response"]
        check.update(
            planned_cells=len(planned),
            launch_intents=len(attempted),
            responses=len(returned),
            unanswered_intents=len(set(attempted) - set(returned)),
            never_attempted_supported=len(supported - set(attempted)),
            interrupted_tails=intent_tail or response_tail,
        )
        manifest = directory / "results/results.json"
        raw, original = checkpoint(manifest, snapshot, inputs)
        if raw is None:
            raw = {
                "schema_version": 1,
                "snapshot_id": snapshot["snapshot_id"],
                "snapshot_provenance": source,
                "suite": snapshot["suite"],
                "games": snapshot["games"],
                "coverage": snapshot.get("coverage", []),
                "records": [],
                "run_provenance": {
                    **source,
                    "execution": {
                        "hardware": {"hostname": claim["hostname"], "affinity": [claim["cpu"]]},
                        "threads": 1,
                        "timeout": 30,
                        "memory_gb": 8,
                        "timing_profile": "diagnostic",
                        "cell_timeout_policy": suite["cell_timeout_policy"],
                        "game_ids": list(games),
                    },
                },
            }
        require(
            raw["snapshot_id"] == snapshot["snapshot_id"]
            and raw["snapshot_provenance"] == source
            and all(raw[k] == snapshot.get(k, []) for k in ("suite", "games", "coverage")),
            "Result snapshot differs",
        )
        run = raw["run_provenance"]
        execution = run["execution"]
        require(
            {k: v for k, v in run.items() if k != "execution"} == source
            and execution["hardware"]["hostname"] == claim["hostname"]
            and execution["hardware"]["affinity"] == [claim["cpu"]]
            and execution["threads"] == 1
            and execution["timeout"] == 30
            and execution["memory_gb"] == 8
            and execution["timing_profile"] == "diagnostic"
            and execution["cell_timeout_policy"] == suite["cell_timeout_policy"]
            and execution["game_ids"] == list(games),
            "Result execution provenance differs",
        )
        methods = {
            name: {
                "source_sha256": source["source_sha256"],
                "software_sha256": identity(source),
                "private": False,
                **(
                    {"parameters": suite["method_parameters"][name]}
                    if suite.get("method_parameters", {}).get(name)
                    else {}
                ),
            }
            for name in suite["methods"]
        }
        require(raw.get("methods", methods) == methods, "Recorded estimator settings differ")
        raw["methods"] = methods
        seen = set()
        for row in raw["records"]:
            key = tuple(row[k] for k in KEYS)
            require(
                key in planned
                and key not in seen
                and row["status"] in {"ok", "failed", "unsupported"},
                "Repeated/foreign result cell",
            )
            seen.add(key)
            require(
                row["timing_profile"] == "diagnostic" and row["official_timing"] is False,
                "Timing relabeled as official",
            )
            if key in supported:
                require(
                    key in returned and all(row.get(k) == v for k, v in returned[key].items()),
                    "Result lacks matching durable response",
                )
                require(row["status"] != "unsupported", "Supported cell mislabeled")
                if row.get("worker"):
                    worker_matches(row["worker"], claim, allocation)
                require(
                    row["status"] != "ok" or row.get("worker"), "Success lacks worker provenance"
                )
            else:
                require(
                    row["status"] == "unsupported"
                    and row["queries"] == row["requested_queries"] == row["wall_seconds"] == 0
                    and row["seconds"] is None,
                    "Unsupported cell performed work",
                )
            validate_scores(row, games[key[0]])
            counts[row["status"]] += 1
        if original:
            require(
                raw["campaign"]
                == {"planned": len(planned), "completed": len(seen), "complete": seen == planned},
                "Checkpoint completion counters differ",
            )
        require(
            not outcome or outcome["status"] != "complete" or (original and seen == planned),
            "False claimed case completion",
        )
        publics = []
        if original:
            public = merge_results([manifest])
            require(set(public["runs"]) == {identity(raw)}, "Original result run identity changed")
            publics.append(public)
        extra = [] if original else list(raw["records"])
        for key in sorted((set(attempted) | (planned - supported)) - seen):
            row = dict(zip(KEYS, key, strict=True)) | {
                "nmse": None,
                "mse": None,
                "error": None,
                "timing_profile": "diagnostic",
                "official_timing": False,
                "timing_scope": f"estimator_with_{games[key[0]].get('oracle', 'table')}_oracle",
            }
            if key in returned:
                row.update(returned[key])
                require(
                    row["status"] != "ok" or row.get("worker"), "Success lacks worker provenance"
                )
                if row.get("worker"):
                    worker_matches(row["worker"], claim, allocation)
                validate_scores(row, games[key[0]])
            elif key in attempted:
                row.update(
                    status="failed",
                    error="OperationalInterruption: launched cell has no complete response.",
                    queries=None,
                    requested_queries=None,
                    seconds=None,
                    wall_seconds=None,
                )
            else:
                row.update(
                    status="unsupported",
                    queries=0,
                    requested_queries=0,
                    seconds=None,
                    wall_seconds=0,
                )
            extra.append(row)
            counts[row["status"]] += 1
        if extra or not publics:
            derived = {
                **raw,
                "records": extra,
                "run_provenance": {
                    **source,
                    "execution": {
                        **execution,
                        "derived_export_view": {
                            "protocol": "pool-explicit-outcomes-v1",
                            "claim_sha256": inputs.hashes[str(directory / "claim.json")],
                            "intent_sha256": inputs.hashes.get(str(directory / "intents.jsonl")),
                            "response_sha256": inputs.hashes.get(
                                str(directory / "responses.jsonl")
                            ),
                            "original_checkpoint_closed": original,
                        },
                    },
                },
            }
            with TemporaryDirectory(prefix="shapiq-pool-public-") as temporary:
                view = Path(temporary) / "results.json"
                view.write_text(json.dumps(derived, allow_nan=False))
                publics.append(merge_results([view]))
        complete = supported == set(attempted) and not intent_tail
        check.update(
            status="complete" if complete else "evaluation_partial",
            complete=complete,
            score_complete=complete
            and all(returned.get(key, {}).get("status") == "ok" for key in supported),
            records=len(seen),
            original_checkpoint_closed=original,
            missing_rows=len(planned - seen),
            uncheckpointed_responses=len(set(returned) - seen),
            derived_rows=len(extra),
        )
        public = publics[0]
        data["games"].extend(public["games"])
        data["coverage"].extend(public["coverage"])
        data["suite"]["budgets_by_game"].update(grids)
        for public in publics:
            for field in ("methods", "runs"):
                for key, value in public[field].items():
                    require(
                        key not in data[field] or data[field][key] == value,
                        "Conflicting report metadata",
                    )
                    data[field][key] = value
            store.extend(public["records"])
    inputs.pin(Path(__file__))
    require(
        {p.name for p in (root / "tasks").iterdir()} == actual_directories, "Task inventory changed"
    )
    require(
        terminal_accounting(config["jobs"]) == accounting,
        "Allocation state changed during collection",
    )
    inputs.stable()
    data["suite"]["budgets"] = sorted(
        {b for grid in data["suite"]["budgets_by_game"].values() for b in grid}
    )
    data["snapshot_id"] = identity(
        {
            "pool_suite": config["suite"]["sha256"],
            "source": source,
            "inputs": inputs.hashes,
            "absent_files": sorted(inputs.absent),
            "runs": sorted(data["runs"]),
        }
    )
    audit = {
        "status": "PASS" if all(c["complete"] for c in cases) else "INCOMPLETE",
        "complete": all(c["complete"] for c in cases),
        "outcome_complete": all(c["complete"] for c in cases),
        "score_complete": all(c.get("score_complete", False) for c in cases),
        "publication_ready": False,
        "scope": "Pool ownership, snapshot integrity and saved estimator score verification; final reference/duplicate and publication checks remain separate.",
        "report_id": data["snapshot_id"],
        "input_hashes": inputs.hashes,
        "absent_files": sorted(inputs.absent),
        "cases": cases,
        "case_statuses": dict(Counter(c["status"] for c in cases)),
        "intended_instances": len(inventory),
        "prepared_targets": len(game_ids),
        "collected_targets": len(data["games"]),
        "rows": len(store),
        "statuses": dict(counts),
        "slurm_accounting": accounting,
    }
    return data, audit
